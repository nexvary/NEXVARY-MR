#pragma once
#include <QVariantMap>
#include <QVariantList>

namespace mr::service {
// Export a technical projection. Raw command output, serials, USB instance IDs,
// paths and arbitrary nested fields remain in the operator's local session only.
inline QVariantMap reportProfile(const QVariantMap &profile) {
    QVariantMap safe;
    for(const auto &key:{"transport","vendor","product","verifiedAtUtc","ro.product.manufacturer",
        "ro.product.model","ro.build.version.release","ro.build.version.sdk","ro.build.version.security_patch"})
        if(profile.contains(key))safe.insert(key,profile.value(key));
    const auto diagnostic=profile.value("diagnostics").toMap();QVariantMap d;
    for(const auto &key:{"schemaVersion","assessment","transport","observedAtUtc","hardwareValidation"})
        if(diagnostic.contains(key))d.insert(key,diagnostic.value(key));
    // These maps are generated by DeviceHealth's bounded observation parser.
    for(const auto &name:{"battery","storage","partitions"}) {
        const auto source=diagnostic.value(name).toMap();QVariantMap part;
        for(const auto &key:{"state","updatesStopped","chargePercent","temperatureC","androidStatusCode",
            "androidHealthCode","mount","totalKiB","usedKiB","availableKiB","scope"})
            if(source.contains(key))part.insert(key,source.value(key));
        if(QString::fromLatin1(name)=="partitions") {
            QVariantList entries;
            for(const auto &row:source.value("entries").toList()) {
                const auto item=row.toMap();QVariantMap entry;
                for(const auto &key:{"name","major","minor","blocksKiB"})if(item.contains(key))entry.insert(key,item.value(key));
                entries.append(entry);
            }
            if(!entries.isEmpty())part.insert("entries",entries);
        }
        d.insert(name,part);
    }
    const auto usb=diagnostic.value("usbDriver").toMap();QVariantMap u;
    for(const auto &key:{"state","interfaceBindingVerified","signatureInventoryAvailable"})
        if(usb.contains(key))u.insert(key,usb.value(key));
    d.insert("usbDriver",u);safe.insert("diagnostics",d);return safe;
}
inline QVariantList reportHistory(const QVariantList &history) {
    QVariantList safe;
    for(const auto &row:history) {
        const auto source=row.toMap();QVariantMap item;
        for(const auto &key:{"transport","atUtc","action","success","sha256","ownerAuthorizationDeclared"})
            if(source.contains(key))item.insert(key,source.value(key));
        safe.append(item);
    }
    return safe;
}
}
