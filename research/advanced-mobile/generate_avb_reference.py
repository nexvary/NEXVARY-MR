#!/usr/bin/env python3
"""Generate synthetic reference images with pinned, separately supplied AOSP avbtool.

No download, device access, firmware repair or production signing is performed.
The temporary RSA key is only for a synthetic fixture and is removed on exit.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import subprocess
import tempfile

SOURCE_URL = "https://android.googlesource.com/platform/external/avb/+/refs/tags/android-15.0.0_r1/avbtool.py?format=TEXT"
TOOL_SHA256 = "78a50c8620985709f2e131cf948dcd66ecc43f09ed735e09d75751a7e21e4eb8"


def run(arguments, expected_success=True):
    result = subprocess.run(arguments, capture_output=True, text=True, timeout=30, check=False)
    if (result.returncode == 0) is not expected_success:
        raise RuntimeError("Unexpected reference tool result: " + result.stdout + result.stderr)
    return result.stdout + result.stderr


def generate(tool, python, openssl, destination):
    if hashlib.sha256(tool.read_bytes()).hexdigest() != TOOL_SHA256:
        raise ValueError("avbtool does not match the reviewed official source hash")
    destination.mkdir(parents=True, exist_ok=True)
    records = []
    with tempfile.TemporaryDirectory(prefix="nexvary-avb-synthetic-") as temporary:
        key = Path(temporary) / "ephemeral-fixture-only.pem"
        run([openssl, "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", str(key)])
        key.chmod(0o600)
        for name, algorithm, index, location, flags, algorithm_id in (
            ("unsigned-property.img", "NONE", "9007199254740993", 7, 1, 0),
            ("signed-property.img", "SHA256_RSA2048", "123", 0, 0, 1),
        ):
            path = destination / name
            args = [python, str(tool), "make_vbmeta_image", "--algorithm", algorithm,
                    "--rollback_index", index, "--rollback_index_location", str(location),
                    "--flags", str(flags), "--prop", "nexvary.fixture:synthetic-only", "--output", str(path)]
            if algorithm_id:
                args.extend(["--key", str(key)])
            run(args)
            info = run([python, str(tool), "info_image", "--image", str(path)])
            (destination / (name + ".info.txt")).write_text(info)
            records.append({"file": name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                            "rollbackIndex": index, "rollbackLocation": location, "flags": flags,
                            "algorithmId": algorithm_id, "descriptorCount": 1,
                            "requiredVersion": re.search(r"Minimum libavb version:\s+(\d+\.\d+)", info).group(1)})
        signed = destination / "signed-property.img"
        valid = run([python, str(tool), "verify_image", "--image", str(signed), "--key", str(key)])
        # Signature begins at auth offset 64 in this official RSA2048 fixture.
        # Check the generated bytes' offset declaration rather than presuming it.
        data = bytearray(signed.read_bytes())
        offset = int.from_bytes(data[48:56], "big")
        size = int.from_bytes(data[56:64], "big")
        if size != 256 or offset > len(data) - 256 - size:
            raise ValueError("Unexpected reference signature layout")
        data[256 + offset] ^= 1
        corrupt = destination / "corrupt-signature.img"
        corrupt.write_bytes(data)
        invalid = run([python, str(tool), "verify_image", "--image", str(corrupt), "--key", str(key)], False)
        records.append(dict(records[1], file=corrupt.name, sha256=hashlib.sha256(data).hexdigest()))
        (destination / "verification.txt").write_text("Synthetic valid signature:\n" + valid + "\nSynthetic corrupted signature (expected rejection):\n" + invalid)
    manifest = {"schemaVersion": 1, "fixtureOnly": True, "sourceUrl": SOURCE_URL,
                "toolSha256": TOOL_SHA256, "toolVersion": run([python, str(tool), "version"]).strip(),
                "signingKey": "ephemeral synthetic key removed after generation; not an OEM or application signing key",
                "images": records}
    (destination / "expected.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    import sys
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--avbtool", type=Path, required=True)
    parser.add_argument("--openssl", default="openssl")
    parser.add_argument("--destination", type=Path, required=True)
    args = parser.parse_args()
    generate(args.avbtool.resolve(), sys.executable, args.openssl, args.destination.resolve())
